    private Object getObjetoSelecionadoNaGrid() {
        int rowCliked = grdAdms.getSelectedRow();
        Object obj = null;
        if (rowCliked >= 0) {
            obj = grdAdms.getModel().getValueAt(rowCliked, -1);
        }
        return obj;
    }


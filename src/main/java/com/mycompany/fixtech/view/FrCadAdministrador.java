    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        Administrador admEditando = (Administrador) this.getObjetoSelecionadoNaGrid();

        if (admEditando == null)
            JOptionPane.showMessageDialog(this, "Primeiro selecione um registro na tabela.");
        else {
            this.limparCampos();
            this.habilitarCampos(true);
            this.preencherFormulario(admEditando);
            this.idAdministradorEditando = admEditando.getIdUsuario();
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        Administrador admExcluido = (Administrador) this.getObjetoSelecionadoNaGrid();

        if (admExcluido == null)
            JOptionPane.showMessageDialog(this, "Primeiro selecione um registro na tabela.");
        else {

            int response = JOptionPane.showConfirmDialog(null,
                    "Deseja exlcuir o Adm  \n("
                    + admExcluido.getNome() + ", "
                    + admExcluido.getIdUsuario() + ") ?",
                    "Confirmar exclusão",
                    JOptionPane.OK_CANCEL_OPTION,
                    JOptionPane.QUESTION_MESSAGE);
            if (response == JOptionPane.OK_OPTION) {

                try {
                    administradorController.excluirAdministrador(admExcluido);

                    administradorController.atualizarTabela(grdAdms);
                    JOptionPane.showMessageDialog(this, "Exclusão feita com sucesso!");
                } catch (AdministradorException ex) {
                    JOptionPane.showMessageDialog(this, ex.getMessage());
                }
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Administrador administradorSalvando = new Administrador();
        try {
            if (idAdministradorEditando > 0) {
                administradorController.atualizarAdministrador(idAdministradorEditando, edtNome.getText(), edtLogin.getText(), edtSenha.getText(), administradorSalvando.getPermission());
            } else {
                administradorController.cadastrarAdministrador(administradorSalvando.getIdUsuario(), edtNome.getText(), edtLogin.getText(), edtSenha.getText(), administradorSalvando.getPermission());
            }
            
            this.idAdministradorEditando = -1L;

            administradorController.atualizarTabela(grdAdms);

            this.habilitarCampos(false);
            this.limparCampos();
        } catch (AdministradorException e) {
            System.err.println(e.getMessage());
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed


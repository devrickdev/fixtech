    private Object getObjetoSelecionadoNaGrid() {
        int rowCliked = grdFeedbacks.getSelectedRow();
        Object obj = null;
        if (rowCliked >= 0) {
            obj = grdFeedbacks.getModel().getValueAt(rowCliked, -1);
        }
        return obj;
    }
    
    

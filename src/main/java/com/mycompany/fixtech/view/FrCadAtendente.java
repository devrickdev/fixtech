    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        Atendente atendenteEditando = (Atendente) this.getObjetoSelecionadoNaGrid();

        if (atendenteEditando == null)
            JOptionPane.showMessageDialog(this, "Primeiro selecione um registro na tabela.");
        else {
            this.limparCampos();
            this.habilitarCampos(true);
            this.preencherFormulario(atendenteEditando);
            this.idAtendenteEditando = atendenteEditando.getIdUsuario();
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        Atendente atendenteExcluido = (Atendente) this.getObjetoSelecionadoNaGrid();

        if (atendenteExcluido == null)
            JOptionPane.showMessageDialog(this, "Primeiro selecione um registro na tabela.");
        else {

            int response = JOptionPane.showConfirmDialog(null,
                    "Deseja exlcuir o Atendente  \n("
                    + atendenteExcluido.getNome() + ", "
                    + atendenteExcluido.getIdUsuario() + ") ?",
                    "Confirmar exclusão",
                    JOptionPane.OK_CANCEL_OPTION,
                    JOptionPane.QUESTION_MESSAGE);
            if (response == JOptionPane.OK_OPTION) {

                try {
                    atendenteController.excluirAtendente(atendenteExcluido);

                    atendenteController.atualizarTabela(grdAtendentes);
                    JOptionPane.showMessageDialog(this, "Exclusão feita com sucesso!");
                } catch (AtendenteException ex) {
                    JOptionPane.showMessageDialog(this, ex.getMessage());
                }
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
       Atendente atendenteSalvando = new Atendente();
        try {
            if (idAtendenteEditando > 0) {
                atendenteController.atualizarAtendente(idAtendenteEditando, edtNome.getText(), edtLogin.getText(), edtSenha.getText(),atendenteSalvando.getPermission());
            } else {
                atendenteController.cadastrarAtendente(atendenteSalvando.getIdUsuario(), edtNome.getText(), edtLogin.getText(), edtSenha.getText(),atendenteSalvando.getPermission());
            }
            
            this.idAtendenteEditando = -1L;

            atendenteController.atualizarTabela(grdAtendentes);

            this.habilitarCampos(false);
            this.limparCampos();
        } catch (AtendenteException e) {
            System.err.println(e.getMessage());
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed


    private Object getObjetoSelecionadoNaGrid() {
        int rowCliked = grdAtendentes.getSelectedRow();
        Object obj = null;
        if (rowCliked >= 0) {
            obj = grdAtendentes.getModel().getValueAt(rowCliked, -1);
        }
        return obj;
    }


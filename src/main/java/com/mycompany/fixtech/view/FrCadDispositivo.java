    private Object getObjetoSelecionadoNaGrid() {
        int rowCliked = grdDispositivos.getSelectedRow();
        Object obj = null;
        if (rowCliked >= 0) {
            obj = grdDispositivos.getModel().getValueAt(rowCliked, -1);
        }
        return obj;
    }


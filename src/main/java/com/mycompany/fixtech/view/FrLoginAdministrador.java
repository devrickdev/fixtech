        Administrador resultado = administradorController.buscarLoginSenha(login,senha);
        if(resultado == null){
            JOptionPane.showMessageDialog(this, "Usuario ou Senha Incorreto!");
        }else{
            FrPainelAdm painelAdm = new FrPainelAdm();
            painelAdm.setVisible(true);
        }

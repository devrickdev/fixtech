    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        atendenteEscolhido = this.getObjetoSelecionadoNaGrid();
        if (atendenteEscolhido == null) {
            int response = JOptionPane.showConfirmDialog(null,
                    "Nenhum atendente foi escolhido. Deseja continuar?",
                    "Confirm",
                    JOptionPane.OK_CANCEL_OPTION,
                    JOptionPane.QUESTION_MESSAGE);
            if (response == JOptionPane.OK_OPTION) {
                dispose();
            }
        } else {
            this.atendimento.setAtendente(atendenteEscolhido);
            dispose();
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

    private void btnSelecionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSelecionarActionPerformed
        atendenteEscolhido = this.getObjetoSelecionadoNaGrid();
        if (atendenteEscolhido == null) {
            areaSelecionado.setText("");
        } else {
            areaSelecionado.setText(atendenteEscolhido.toString());
        }
    }//GEN-LAST:event_btnSelecionarActionPerformed


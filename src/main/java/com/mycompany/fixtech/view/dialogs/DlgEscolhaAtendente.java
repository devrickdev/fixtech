        public Atendente getObjetoSelecionadoNaGrid() {
            int linhaSelecionada = grdListagem.getSelectedRow();
            if (linhaSelecionada >= 0) {
                TMCadAtendente tmCadAtendente = (TMCadAtendente) grdListagem.getModel();
                Atendente atendente = tmCadAtendente.getObjetoAtendente(linhaSelecionada);
                return atendente;
            }
            return null;
        }

